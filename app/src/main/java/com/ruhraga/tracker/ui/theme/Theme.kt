@Immutable
data class RuhRagaExtendedColors(
    val subtleBorder: Color = SubtleBorder,
    val primaryFixed: Color = PrimaryFixed,
    val secondaryFixed: Color = SecondaryFixed,
    val ragaVibrantOrange: Color = RagaVibrantOrange
)

val LocalRuhRagaExtendedColors = staticCompositionLocalOf { RuhRagaExtendedColors() }

object RuhRagaTheme {
    val extendedColors: RuhRagaExtendedColors
        @Composable
        get() = LocalRuhRagaExtendedColors.current
}

@Composable
fun RuhRagaTheme(
    darkTheme: Boolean = false,
    content: @Composable () -> Unit
) {
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                WindowCompat.getInsetsController(window, view).apply {
                    isAppearanceLightStatusBars = !darkTheme
                    isAppearanceLightNavigationBars = !darkTheme
                }
            }
        }
    }

    val extended = if (darkTheme) {
        RuhRagaExtendedColors()
    } else {
        RuhRagaExtendedColors(
            subtleBorder = LightSubtleBorder,
            primaryFixed = LightPrimaryContainer,
            secondaryFixed = LightSecondaryContainer,
            ragaVibrantOrange = RagaVibrantOrange
        )
    }

    CompositionLocalProvider(
        LocalRuhRagaExtendedColors provides extended
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) RuhRagaDarkColorScheme else RuhRagaLightColorScheme,
            typography = RuhRagaTypography,
            content = content
        )
    }
}
